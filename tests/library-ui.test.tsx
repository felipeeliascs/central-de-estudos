const { rpc }=vi.hoisted(()=>({rpc:vi.fn()}));
vi.mock("../src/repository",()=>({supabase:{rpc,from:()=>({select:()=>({eq:()=>({maybeSingle:async()=>({data:{document:{...sample,sources:[{title:"Página oficial do concurso",url:"https://example.test/concurso"}]}},error:null})})})})}}));
