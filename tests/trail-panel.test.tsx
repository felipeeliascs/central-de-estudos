import { afterEach, expect, it, vi } from "vitest";
import { cleanup, render, screen, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { TrailPanel } from "../src/TrailPanel";
import { demoData,demoUser } from "../src/demo";
afterEach(()=>{cleanup();localStorage.clear();vi.useRealTimers();});
it("gera trilha na página, respeita pré-requisito e preserva conclusão após importar configuração",async()=>{
  vi.useFakeTimers({toFake:["Date"]});vi.setSystemTime(new Date("2026-11-27T18:00:00Z"));
  const user=userEvent.setup();
  render(<main id="conteudo"><TrailPanel snapshot={demoData()} user={demoUser} demo close={()=>{}} study={()=>{}} prompts={()=>{}}/></main>);
  await user.click(await screen.findByRole("button",{name:"Gerar trilha da semana"}));
  await screen.findByText("Trilha salva.");
  const today=new Intl.DateTimeFormat("sv-SE",{timeZone:"America/Sao_Paulo"}).format(new Date());
  const dayRows=screen.getAllByRole("button",{name:"Concluir estudo"});
  expect(dayRows).toHaveLength(2);
  expect((dayRows[0] as HTMLButtonElement).disabled).toBe(false);
  expect((dayRows[1] as HTMLButtonElement).disabled).toBe(true);
  await user.click(dayRows[0]);
  await screen.findByText(/1 estudo concluído/);
  await user.click(screen.getByRole("button",{name:"Configurações da Trilha"}));
  const raw={schema_version:"1.0",type:"study_trail",contest_id:"demo-contest",topics:[{topic_id:"demo-topic",requires:[],minutes:45,estimated_priority:"high"}]};
  await user.click(screen.getByLabelText("JSON de Trilhas"));await user.paste(JSON.stringify(raw));
  await user.click(screen.getByRole("button",{name:"Gerar prévia da trilha"}));
  await screen.findByRole("heading",{name:"Prévia da sequência"});
  await user.click(screen.getByRole("button",{name:"Confirmar configuração"}));
  const stored=JSON.parse(localStorage.getItem("central-trail:"+demoUser+":demo-contest")!);
  expect(stored.state.config.topics.find((t:{topic_id:string})=>t.topic_id==="demo-topic").estimated_priority).toBe("high");
  expect(stored.state.weeks[0].sessions.every((s:{day:string})=>s.day>=today)).toBe(true);
  expect(stored.state.weeks[0].sessions.filter((s:{done:boolean})=>s.done)).toHaveLength(1);
  expect(within(screen.getByRole("main")).queryByRole("dialog")).toBeNull();
});
